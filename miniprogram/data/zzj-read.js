function focusOf(key) {
  for (var i = 0; i < FOCUS.length; i++) {
    if (FOCUS[i].key === key) return FOCUS[i];
  }
  return FOCUS[0];
}

// 生成完整解读。pick 为 zzj.pickByNumbers / pickRandom 的结果。
function buildReading(pick, focusKey, question) {
  var a = zzj.palace(pick.first);
  var b = zzj.palace(pick.second);
  var c = zzj.palace(pick.result);
  var focus = focusOf(focusKey);
  var pos = [
    { name: '起', palace: a, slot: 'start' },
    { name: '中', palace: b, slot: 'mid' },
    { name: '果', palace: c, slot: 'end' }
  ];
  var layers = pos.map(function (p, i) {
    return {
      name: p.name,
      tone: p.palace.tone,
      trad: p.palace.trad,
      plain: PLAIN[p.palace.key][p.slot],
      hint: LAYER_HINT[p.palace.key],
      open: i === 0 // 默认只展开第一层，逐层点开
    };
  });
  var acts = ACTIONS[c.key] || [];
  var actions = [
    (FOCUS_LEAD[focus.key] || '') + acts[0],
    acts[1],
    acts[2]
  ];
  return {
    question: String(question || '').trim(),
    focus: { key: focus.key, label: focus.label, hint: focus.hint },
    headline: HEADLINE[c.key][focus.key],
    layers: layers,
    actions: actions,
    followups: (FOLLOWUPS[c.key] || []).map(function (f) {
      return { q: f.q, a: f.a, open: false };
    }),
    timing: (require('./zzj-ext.js').TIMING || {})[c.key] || '',
    closing: CLOSING[c.key]
  };
}

module.exports = {
  FOCUS: FOCUS,
  PLAIN: PLAIN,
  LAYER_HINT: LAYER_HINT,
  HEADLINE: HEADLINE,
  ACTIONS: ACTIONS,
  FOLLOWUPS: FOLLOWUPS,
  CLOSING: CLOSING,
  buildReading: buildReading
};
